// Builds the data embedded in the app:
//   js/data/alternates.js — DOTE TAM "Alternate Subjects for Theory Subjects" (all courses / regulations)
//   js/data/timetable.js  — parsed Board Examinations time table
//
// Usage (from the repo root):
//   npm i --no-save pdfjs-dist@4.10.38
//   node tools/build-data.mjs --timetable "TT/<time table>.pdf"      # crawl + parse
//   node tools/build-data.mjs --alternates-json raw.json ...         # reuse an earlier crawl
//   node tools/build-data.mjs --skip-alternates --timetable ...      # time table only
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) => (v.startsWith('--') ? [...a, [v.slice(2), all[i + 1]?.startsWith('--') ? true : all[i + 1] ?? true]] : a), []));
const ALT_URL = args.url || 'http://112.133.214.77/schalt/O26.php';

/* ---------- alternate subjects ---------- */
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function get(q) {
  for (let i = 0; i < 4; i++) {
    try {
      const r = await fetch(ALT_URL + q, { signal: AbortSignal.timeout(30000) });
      if (r.ok) return await r.text();
    } catch {}
    await sleep(1500 * (i + 1));
  }
  throw new Error('Could not fetch ' + ALT_URL + q);
}
const options = (html, name) => {
  const i = html.indexOf(`name='${name}'`);
  if (i < 0) return [];
  const seg = html.slice(i, html.indexOf('</div>', i));
  return [...seg.matchAll(/<option value='?([^'>\s]+)'?/g)].map((m) => m[1]);
};
const clean = (s) => s.replace(/<br\s*\/?>/g, ' — ').replace(/<[^>]*>/g, '').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

async function crawlAlternates() {
  const home = await get('');
  const title = clean(home.match(/<div class='text-center mb-3 fw-bold'>([\s\S]*?)<\/div>/)[1]);
  const courses = options(home, 'ncno');
  const rows = [];
  const queue = [...courses];
  let done = 0;
  await Promise.all([0, 1].map(async () => {
    while (queue.length) {
      const c = queue.shift();
      for (const regl of options(await get(`?ncno=${c}`), 'regl')) {
        const html = await get(`?ncno=${c}&regl=${encodeURIComponent(regl)}&sem=ALL`);
        for (const tr of html.split('<tr').slice(1)) {
          const td = [...tr.matchAll(/<td[^>]*>([\s\S]*?)<\/td>/g)].map((m) => clean(m[1]));
          if (td.length === 8) rows.push(td);
        }
      }
      if (++done % 20 === 0) console.log(`  ${done}/${courses.length} courses, ${rows.length} rows`);
    }
  }));
  return { title, fetchedAt: new Date().toISOString(), courses, rows };
}

// Compact: one string table for names, rows grouped by "course|regulation".
function packAlternates({ title, fetchedAt, rows }) {
  const names = [], nameIdx = new Map(), exams = [], examIdx = new Map();
  const idx = (s, list, map) => (map.has(s) ? map.get(s) : (map.set(s, list.length), list.push(s), list.length - 1));
  const tables = {};
  for (const [course, regl, sem, col, oldName, code, name, exam] of rows) {
    (tables[`${course}|${regl}`] ||= []).push([+sem, +col, idx(oldName, names, nameIdx), code.trim(), idx(name, names, nameIdx), idx(exam, exams, examIdx)]);
  }
  return { source: ALT_URL, title, fetchedAt, rowCount: rows.length, exams, names, tables };
}

/* ---------- main ---------- */
const outDir = path.join(ROOT, 'js', 'data');
fs.mkdirSync(outDir, { recursive: true });
const banner = (what) => `// Generated by tools/build-data.mjs on ${new Date().toISOString()} — ${what}. Do not edit by hand.\n`;

if (!args['skip-alternates']) {
  const raw = args['alternates-json'] ? JSON.parse(fs.readFileSync(args['alternates-json'], 'utf8')) : (console.log('Crawling', ALT_URL), await crawlAlternates());
  const packed = packAlternates(raw);
  fs.writeFileSync(path.join(outDir, 'alternates.js'), banner('DOTE alternate subjects') + `export default ${JSON.stringify(packed)};\n`);
  console.log(`alternates.js: ${packed.rowCount} rows, ${Object.keys(packed.tables).length} course/regulation tables`);
}

if (args.timetable) {
  const pdfjs = await import(args.pdfjs ? pathToFileURL(args.pdfjs).href : 'pdfjs-dist/legacy/build/pdf.mjs');
  const { parseTimetable, packTimetable } = await import(pathToFileURL(path.join(ROOT, 'js', 'ttparser.js')).href);
  const tt = packTimetable(await parseTimetable(pdfjs, new Uint8Array(fs.readFileSync(args.timetable))), path.basename(args.timetable));
  fs.writeFileSync(path.join(outDir, 'timetable.js'), banner('DOTE time table') + `export default ${JSON.stringify(tt)};\n`);
  console.log(`timetable.js: ${tt.rows.length} entries (${tt.meta.version})`);
}
