// Build js/data/equivalents.js from DOTE's equivalent-subject table (tab-separated, Windows-1252):
//   course · subject code · subject name · sem · … · scheme (K/L/M/N/R) · equivalent subject code
// Only old-scheme rows (K, L, M, N) are kept: they map a course's old subject to the code that replaced it.
// Usage: node tools/build-equiv.mjs "path/to/equivalents.csv"
import fs from 'fs';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/build-equiv.mjs <equivalents.csv>');
  process.exit(1);
}
const text = new TextDecoder('windows-1252').decode(fs.readFileSync(src));

// Tab-separated, but some names are quoted and contain tabs or quotes.
function parseLine(line) {
  const out = [];
  let cur = '', q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === '\t') { out.push(cur); cur = ''; }
    else cur += ch;
  }
  out.push(cur);
  return out.map((f) => f.replace(/\s+/g, ' ').trim());
}

const rows = [];
const skipped = [];
for (const line of text.split(/\r?\n/)) {
  if (!line.trim()) continue;
  const f = parseLine(line);
  // scheme is the single letter just before the last field (columns 5–7 vary)
  const target = f[f.length - 1];
  const scheme = (f[f.length - 2] || '').toUpperCase();
  const [course, code, name, sem] = f;
  if (!/^[KLMN]$/.test(scheme)) { if (scheme !== 'R') skipped.push(line); continue; }
  if (!course || !code || !target || code === target) { skipped.push(line); continue; }
  rows.push([course, code, name.replace(/�/g, '-'), +sem || 0, scheme, target]);
}

const out = `// Generated by tools/build-equiv.mjs on ${new Date().toISOString()} — DOTE equivalent subjects. Do not edit by hand.
// rows: [course, old subject code, old subject name, sem, scheme (K/L/M/N), equivalent subject code]
export default ${JSON.stringify({ meta: { file: src.split(/[\\/]/).pop(), rows: rows.length }, rows })};
`;
fs.writeFileSync(new URL('../js/data/equivalents.js', import.meta.url), out);
console.log(`${rows.length} old-scheme rows written to js/data/equivalents.js; ${skipped.length} other line(s) skipped`);
for (const s of skipped) console.log('  skipped:', s.slice(0, 120));
