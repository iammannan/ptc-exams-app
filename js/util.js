// Shared helpers for the app modules.
const PDFJS = 'https://cdn.jsdelivr.net/npm/pdfjs-dist@4.10.38/build/pdf.min.mjs';
const PDFJS_WORKER = 'https://cdn.jsdelivr.net/npm/pdfjs-dist@4.10.38/build/pdf.worker.min.mjs';
const JSPDF = 'https://cdn.jsdelivr.net/npm/jspdf@2.5.2/dist/jspdf.umd.min.js';
const AUTOTABLE = 'https://cdn.jsdelivr.net/npm/jspdf-autotable@3.8.4/dist/jspdf.plugin.autotable.min.js';
const EXCELJS = 'https://cdn.jsdelivr.net/npm/exceljs@4.4.0/dist/exceljs.min.js';
const JSZIP = 'https://cdn.jsdelivr.net/npm/jszip@3.10.1/dist/jszip.min.js';

export const $ = (id) => document.getElementById(id);
export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

let pdfjsP;
export function loadPdfjs() {
  pdfjsP ??= import(PDFJS).then((m) => {
    m.GlobalWorkerOptions.workerSrc = PDFJS_WORKER;
    return m;
  });
  return pdfjsP;
}

function loadScript(src) {
  return new Promise((resolve, reject) => {
    const s = document.createElement('script');
    s.src = src;
    s.onload = resolve;
    s.onerror = () => reject(new Error('Could not load ' + src));
    document.head.appendChild(s);
  });
}
let jspdfP;
export const loadJsPdf = () => (jspdfP ??= loadScript(JSPDF).then(() => loadScript(AUTOTABLE)).then(() => window.jspdf.jsPDF));
let exceljsP;
export const loadExcelJs = () => (exceljsP ??= loadScript(EXCELJS).then(() => window.ExcelJS));
let jszipP;
export const loadJsZip = () => (jszipP ??= loadScript(JSZIP).then(() => window.JSZip));

let toastTimer;
export function toast(msg) {
  const t = $('toast');
  t.textContent = msg;
  t.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => (t.hidden = true), 3200);
}

export const pref = {
  get(k) { try { return localStorage.getItem('ptc.' + k) ?? ''; } catch { return ''; } },
  set(k, v) { try { localStorage.setItem('ptc.' + k, v); } catch {} },
};

export function download(name, blob) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

export const slug = (s) => String(s).replace(/[^\w-]+/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');

export function downloadCsv(name, header, rows) {
  const q = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
  const csv = [header.map(q).join(','), ...rows.map((r) => r.map(q).join(','))].join('\r\n');
  download(name, new Blob(['﻿' + csv], { type: 'text/csv' }));
}

// Wire a drop zone + file input pair to a handler that receives the chosen PDF files.
export function bindDropzone(zone, input, onFiles) {
  input.addEventListener('change', (e) => {
    onFiles(e.target.files);
    e.target.value = '';
  });
  ['dragenter', 'dragover'].forEach((ev) => zone.addEventListener(ev, (e) => { e.preventDefault(); zone.classList.add('drag'); }));
  ['dragleave', 'drop'].forEach((ev) => zone.addEventListener(ev, (e) => { e.preventDefault(); zone.classList.remove('drag'); }));
  zone.addEventListener('drop', (e) => onFiles(e.dataTransfer.files));
}

export const pdfFiles = (list) => [...list].filter((f) => /\.pdf$/i.test(f.name) || f.type === 'application/pdf');

export function pdfFooter(doc) {
  const W = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  doc.setFont('helvetica', 'normal').setFontSize(8).setTextColor(120);
  doc.text(`Generated by PTC Exams App by Mannar Mannan V on ${new Date().toLocaleString('en-IN')}`, 14, h - 7);
  doc.text(`Page ${doc.internal.getNumberOfPages()}`, W - 14, h - 7, { align: 'right' });
  doc.setTextColor(0);
}
